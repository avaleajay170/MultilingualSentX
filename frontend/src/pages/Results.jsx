import { useLocation, useNavigate } from "react-router-dom";

function Results() {
  const location = useLocation();
  const navigate = useNavigate();
  const data = location.state;

  const hasResult = !!data?.result;
  const result = data?.result;

  const sentimentEmoji = {
    Positive: "😊",
    Negative: "😞",
    Neutral: "😐"
  };

  if (!hasResult) {
    return (
      <div className="results-page">
        <div className="results-header">
          <span className="results-badge">
            ANALYSIS RESULTS
          </span>

          <h1>Sentiment Results</h1>

          <p>
            No analysis has been run yet in this session. Head to the
            Analysis page to analyze a comment first.
          </p>
        </div>

        <button
          className="analyze-button"
          onClick={() => navigate("/analysis")}
        >
          Go to Analysis
        </button>
      </div>
    );
  }

  return (
    <div className="results-page">

      {/* =========================
          HEADER
      ========================= */}

      <div className="results-header">
        <span className="results-badge">
          ANALYSIS RESULTS
        </span>

        <h1>Sentiment Results</h1>

        <p>
          View the sentiment prediction and explanation
          generated by the multilingual AI model.
        </p>
      </div>


      {/* =========================
          MAIN SENTIMENT CARD
      ========================= */}

      <div className="result-main-card">

        <div className="result-title">

          <div>
            <h2>Overall Sentiment</h2>

            <p>
              AI-generated sentiment classification
            </p>
          </div>

          <span className="result-status">
            Complete
          </span>

        </div>


        <div className="sentiment-result">

          <div className="sentiment-circle">
            <span>
              {sentimentEmoji[result?.sentiment] || "—"}
            </span>
          </div>


          <div className="sentiment-details">

            <span className="result-label">
              SENTIMENT
            </span>

            <h3>
              {result?.sentiment || "Unknown"}
            </h3>

            <p>
              "{data?.inputText || result?.text || "No comment available"}"
            </p>

          </div>

        </div>

      </div>


      {/* =========================
          RESULT INFORMATION
      ========================= */}

      <div className="result-grid">


        {/* Confidence */}

        <div className="result-card">

          <span className="result-card-label">
            CONFIDENCE
          </span>

          <h3>
            {result?.sentiment_confidence != null
              ? `${(result.sentiment_confidence * 100).toFixed(1)}%`
              : "N/A"}
          </h3>

          <p>
            Model confidence score
          </p>

        </div>


        {/* Aspect */}

        <div className="result-card">

          <span className="result-card-label">
            ASPECT
          </span>

          <h3>
            {result?.aspect || "Unknown"}
          </h3>

          <p>
            Detected aspect
            {result?.aspect_confidence
              ? ` (${(result.aspect_confidence * 100).toFixed(1)}%)`
              : ""}
          </p>

        </div>


        {/* Model */}

        <div className="result-card">

          <span className="result-card-label">
            MODEL
          </span>

          <h3>
            {result?.model_used || "MuRIL"}
          </h3>

          <p>
            Analysis model
          </p>

        </div>

      </div>


      {/* =========================
          EXPLAINABLE AI
      ========================= */}

      <div className="explanation-card">

        <h2>
          Explainable AI Insights
        </h2>

        <p>
          The explanation generated by the AI model
          will appear here when available.
        </p>


        <div className="explanation-placeholder">

          <span>
            💡
          </span>

          <div>

            <h3>
              Explanation
            </h3>

            <p>
              {result?.explanation?.llm_rationale ||
                "Explanation is not available for this analysis yet."}
            </p>

          </div>

        </div>

      </div>


      {/* =========================
          ACTION BUTTONS
      ========================= */}

      <div
        style={{
          display: "flex",
          justifyContent: "center",
          gap: "15px",
          marginTop: "30px",
          marginBottom: "40px"
        }}
      >

        <button
          className="analyze-button"
          onClick={() => navigate("/analysis")}
        >
          Analyze Another
        </button>

        <button
          className="analyze-button"
          onClick={() => navigate("/dashboard")}
        >
          Dashboard
        </button>

      </div>

    </div>
  );
}

export default Results;